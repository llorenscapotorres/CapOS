; Creating my own BIOS, or in Esperanto, my own BEES

; Assemble for 16-bit real mode
bits 16

; Addresses are calculated relative to file start
org 0x0000

PCI_CONFIG_ADDRESS equ 0x0CF8
PCI_CONFIG_DATA    equ 0x0CFC

start:
    ; Disable interrupts: no Interrupt Descriptor Table is set up yet,
    ; so an interrupt firing now would jump to garbage and crash the CPU
    ;
    ; In real mode, every interrupt (hardware or software) looks up its handler address
    ; in a table called the IVT (Interrupt Vector Table), normally located at 0x0000:0x0000.
    ; Since this BIOS just started, that table isn't initialized with valid values yet.
    cli

    xor ax, ax ; Set ax = 0
    mov ds, ax ; Data Segment = 0
    mov es, ax ; Extra Segment = 0
    mov ss, ax ; Stack Segment = 0
    mov sp, 0x7C00 ; Stack Pointer, grows downward from 0x7C00

    call setup_ivt
    call pci_enable_vga
    call setup_vga_text_mode
    call load_font
    call load_bootloader
    ; jump to the bootloader we just loaded, remember it started at 0x7C00
    jmp 0x0000:0x7C00 ; address = 0x0000 * 16 + 0x7C00 = 0x7C00

; =============================================================================
; pci_enable_vga
;
; Real BIOSes enumerate the PCI bus during POST and set each device's
; Command register bits so it actually responds to I/O/memory accesses.
; Since BEES *is* the BIOS, nobody has done this yet, which means our VGA
; register writes and framebuffer writes have been silently going nowhere:
; the device exists but ignores all I/O/memory accesses by default at reset.
;
; This scans bus 0 (device 0-31, function 0 only, which covers the default
; QEMU machine layout) for a device whose Class Code is 0x03 (Display
; Controller), and sets Command register bits 0 (I/O Space Enable) and
; 1 (Memory Space Enable) for it.
;
; Uses 32-bit registers (eax/ecx/edx) even though we're in 16-bit real mode:
; valid on any 386+ CPU, NASM adds the needed operand-size prefixes.
; =============================================================================
pci_enable_vga:
    pushad
    xor ecx, ecx            ; ecx = device number being probed (0-31)

.scan_loop:
    ; CONFIG_ADDRESS for (bus=0, device=ecx, function=0, register=0x00)
    ; i.e. reading the Vendor/Device ID register, to check if a device
    ; actually exists in this slot.
    mov eax, ecx
    shl eax, 11              ; device number goes in bits [15:11]
    or eax, 0x80000000       ; bit 31 = enable config space access
    mov dx, PCI_CONFIG_ADDRESS
    out dx, eax

    mov dx, PCI_CONFIG_DATA
    in eax, dx
    cmp ax, 0xFFFF            ; Vendor ID 0xFFFF = empty slot, nothing here
    je .next_device

    ; Device exists: read its Class Code register (offset 0x08).
    ; Bits [31:24] of that dword = Base Class Code. 0x03 = Display Controller.
    mov eax, ecx
    shl eax, 11
    or eax, 0x80000008        ; same device, register offset 0x08
    mov dx, PCI_CONFIG_ADDRESS
    out dx, eax
    mov dx, PCI_CONFIG_DATA
    in eax, dx
    shr eax, 24
    cmp al, 0x03
    jne .next_device

    ; Found the display controller. Read-modify-write its Command register
    ; (offset 0x04) to set bit 0 (I/O Space Enable) and bit 1 (Memory Space
    ; Enable), leaving every other bit untouched.
    mov eax, ecx
    shl eax, 11
    or eax, 0x80000004
    mov dx, PCI_CONFIG_ADDRESS
    out dx, eax
    mov dx, PCI_CONFIG_DATA
    in eax, dx
    or ax, 0x0003
    out dx, eax
    jmp .done                 ; assume a single VGA device; stop scanning

.next_device:
    inc ecx
    cmp ecx, 32
    jl .scan_loop

.done:
    popad
    ret

; ==============================================================================
; setup_vga_text_mode
;
; Programs the VGA card's hardware registers directly (no real BIOS / int 0x10 available,
; since BEES IS the BIOS). This replicates what a real BIOS does during POST when
; setting video mode 3 (80x25 text, 16 colors).
;
; The VGA exposes 5 independent register groups, each with its own I/O ports:
;   - Misc Output: single write-only port 0x3C2
;   - Sequencer (SR): index port 0x3C4, data port 0x3C5
;   - CRT Controller (CR): index port 0x3D4, data port 0x3D5
;   - Graphics Ctrl (GR): index port 0x3CE, data port 0x3CF
;   - Attribute Ctrl (AR): single port 0x3C0 for both index and data, toggled
;                          internally by a flip-flop
;
; Clobbers: ax, cx, dx, si
; ==============================================================================
setup_vga_text_mode:
    push ax
    push cx
    push dx
    push si
    push ds

    mov ax, cs
    mov ds, ax ; tables are in the same segment as code

    ; 1) Misc Output Register (single write, no index needed)
    ; 0x67 = color mode, 28.322 MHz pixel clock (needed for 80-col text),
    ; enable RAM, negative h/v sync polarity for this mode
    mov dx, 0x3C2
    mov al, 0x67
    out dx, al

    ; 2) Sequence registers (SR00-SR04)
    ; SR02 = 0x03 is the important one for text mode: it enables write to
    ; plane 0 (character codes) and plane 1 (attributes/font) at once
    mov si, seq_data
    mov cx, 5
    mov dx, 0x3C4
.seq_loop:
    mov al, [si] ; register index (0, 1, 2, 3, 4, ...)
    out dx, al ; select register
    inc dx ; index port --> data port (0x3C4 -> 0x3C5)
    mov al, [si+1]
    out dx, al ; write value
    dec dx ; back to index port for next iteration
    add si, 2
    loop .seq_loop

    ; 3) CRT Controller registers (CR00-CR18)
    ; CRTC registers 0-7 are "protected" by bit 7 of CR11 (Vertical Retrace End).
    ; If that bit is set, writes to CR00-CR07 are ignored.
    ; So we first force it clear, THEN write the whole table index
    ; order 0x00 -> 0x18. CR11 gets its real (protected) value naturally when we
    ; reach it mid-loop, by which point CR00-CR06 are already set.
    mov dx, 0x3D4
    mov al, 0x11 ; select CR11
    out dx, al
    inc dx
    mov al, 0x00 ; temporarily clear the protect bit (bit 7)
    out dx, al
    dec dx

    mov si, crtc_data
    mov cx, 25
.crtc_loop:
    mov al, [si]
    out dx, al
    inc dx
    mov al, [si+1]
    out dx, al
    dec dx
    add si, 2
    loop .crtc_loop

    ; 4) Graphics Controller registers (GR00-GR08)
    ; In text mode these mostly configure "pass-through" behaviour so
    ; that what the Sequencer/CRTC write ends up visible as characters.
    mov si, gc_data
    mov cx, 9
    mov dx, 0x3CE
.gc_loop:
    mov al, [si]
    out dx, al
    inc dx
    mov al, [si+1]
    out dx, al
    dec dx
    add si, 2
    loop .gc_loop

    ; 5) Attribute Controller registers (AR00-AR14)
    ; Uses ONE port (0x3C0) for both index and data, toggled by an internal flip-flop.
    ; Reading the input status register (0x3DA) resets that flip-flop back to
    ; "expecting an index next", so we do that before every index write to stay in sync.
    mov si, ac_data
    mov cx, 21
.ac_loop:
    mov dx, 0x3DA
    in al, dx ; reset flip-flop to "index" state
    mov dx, 0x3DA
    in al, dx
    mov dx, 0x3C0
    mov al, [si]
    out dx, al ; write index
    mov al, [si+1]
    out dx, al ; write data
    add si, 2
    loop .ac_loop

    ; Re-enable video output: index 0x20 has bit 5 (Palette Address Source) set,
    ; which was kept clear (blanked) while we were programming above.
    mov dx, 0x3DA
    in al, dx ; reset flip-flop once more
    mov dx, 0x3C0
    mov al, 0x20
    out dx, al

    ; -------------------------------------------------------------------
    ; 5.5) DAC / color palette — ports 0x3C8 (index) / 0x3C9 (data: R,G,B)
    ;    The Attribute Controller only selects WHICH DAC entry each color
    ;    attribute (0-15) maps to. The DAC decides what RGB that entry
    ;    actually renders as. Left uninitialized, DAC entries are commonly
    ;    all zero (black) -> "white on black" text becomes black-on-black,
    ;    i.e. invisible even though it's being written correctly.
    ; -------------------------------------------------------------------
    mov si, dac_data
    mov cx, 16
    mov dx, 0x3C8
.dac_loop:
    mov al, [si]        ; DAC entry index
    out dx, al
    inc dx              ; 0x3C8 -> 0x3C9 (data port)
    mov al, [si+1]
    out dx, al          ; Red   (0-63)
    mov al, [si+2]
    out dx, al          ; Green (0-63)
    mov al, [si+3]
    out dx, al          ; Blue  (0-63)
    dec dx              ; back to 0x3C8 for next index
    add si, 4
    loop .dac_loop

    ; 6) Clear the text buffer: whatever was in VGA memory before (garbage, 
    ; a previous mode's contents) is still there. Fill all 80x25 cells with
    ; space (0x20) + white-on-black attribute (0x07).
    push es
    mov ax, 0xB800
    mov es, ax
    xor di, di
    mov cx, 80*25 ; one write per character cell
    mov ax, 0x0720 ; ah=0x07 attribute, al=0x20 space
.clear_loop:
    stosw
    loop .clear_loop
    pop es

    pop ds
    pop si
    pop dx
    pop cx
    pop ax
    ret

