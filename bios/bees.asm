; ==============================================================================
; load_font
;
; VGA text mode renders each character by looking up its 8x16 pixel bitmap in
; "plane 2" of video memory (the character generator) - a piece of VRAM that
; setup_vga_text_mode never touches, and that QEMU's emulated VGA card does
; NOT preload with anything. Without this routine, every character prints
; with the right code + attribute byte (verified directly by dumping 0xB8000
; in the QEMU monitor) but renders as a blank glyph, because there is no
; pixel data anywhere for the VGA to draw.
;
; This mirrors what every real VGA BIOS does once during POST:
;   1. Temporarily reprogram the Sequencer + Graphics Controller so CPU
;      writes go, sequentially, into plane 2 ONLY - exposed at segment
;      0xA000 instead of the usual 0xB800 text buffer.
;   2. Copy an embedded 8x16 bitmap font there: one 32-byte hardware slot
;      per character code (0-255), of which only the first 16 bytes
;      (16 scanlines) are used.
;   3. Restore the Sequencer/Graphics Controller to the exact values
;      setup_vga_text_mode already programmed, so normal text-mode
;      addressing (planes 0+1 interleaved at 0xB800) works again.
;
; Must run AFTER setup_vga_text_mode (step 3 restores ITS register values)
; and BEFORE anything tries to print a character.
;
; Clobbers: ax, cx, dx, si, di, ds, es
; ==============================================================================
load_font:
    push ax
    push cx
    push dx
    push si
    push di
    push ds
    push es

    ; font_data lives in this same ROM image (CS segment), but DS was reset
    ; to 0x0000 by 'start' (needed for the IVT/BDA) - the exact same
    ; segment mismatch bug we already fixed in setup_vga_text_mode. Align DS
    ; with CS so "mov si, font_data" / "rep movsb" below actually reads the
    ; real table instead of zeroed low RAM.
    mov ax, cs
    mov ds, ax

    cld ; make sure movsb increments si/di (should already be clear at reset)

    ; ---- Step 1: redirect CPU writes to plane 2 only, sequential addressing ----

    ; Sequencer index 2 (Map Mask register): only bit 2 set -> only plane 2
    ; accepts writes (planes 0/1/3 ignore them).
    mov dx, 0x3C4
    mov al, 0x02
    out dx, al
    inc dx
    mov al, 0x04
    out dx, al
    dec dx

    ; Sequencer index 4 (Memory Mode register): bit1=1 Extended Memory (lets
    ; us reach beyond the first 64K), bit2=1 disables Odd/Even addressing so
    ; consecutive addresses land in consecutive bytes of the SAME plane,
    ; instead of alternating between planes like normal text mode does.
    mov al, 0x04
    out dx, al
    inc dx
    mov al, 0x06
    out dx, al
    dec dx

    ; Graphics Controller index 4 (Read Map Select): point reads at plane 2
    ; too, for symmetry with the write side above (not required just to
    ; write the font, but keeps read/write consistent while in this layout).
    mov dx, 0x3CE
    mov al, 0x04
    out dx, al
    inc dx
    mov al, 0x02
    out dx, al
    dec dx

    ; Graphics Controller index 5 (Graphics Mode register): bit4=0 disables
    ; "Host Odd/Even", matching the sequential addressing enabled above.
    mov al, 0x05
    out dx, al
    inc dx
    mov al, 0x00
    out dx, al
    dec dx

    ; Graphics Controller index 6 (Miscellaneous register): Memory Map
    ; Select (bits 3-2) = 01, which exposes the CPU window at
    ; 0xA0000-0xAFFFF instead of the usual 0xB8000 text-buffer window
    ; (bits 3-2 = 11, what setup_vga_text_mode leaves it as).
    mov al, 0x06
    out dx, al
    inc dx
    mov al, 0x04
    out dx, al
    dec dx

    ; ---- Step 2: copy the embedded font into plane 2 ----
    ; es:di walks the 0xA0000 window; ds:si walks font_data.
    mov ax, 0xA000
    mov es, ax
    xor di, di
    mov si, font_data
    mov cx, 256           ; 256 characters

.char_loop:
    push cx
    mov cx, 16             ; 16 bytes per glyph (8 pixels wide, 16 scanlines)
    rep movsb              ; copies [ds:si] -> [es:di], si += cx, di += cx
    add di, 16              ; each character has a 32-byte hardware slot -
                             ; skip the 16 unused trailing bytes (scanlines
                             ; 16-31, which CR09's "Maximum Scan Line = 15"
                             ; never fetches for display anyway)
    pop cx
    loop .char_loop

    ; ---- Step 3: restore normal text-mode addressing ----
    ; Exactly the values setup_vga_text_mode already established, for planes
    ; 0+1 interleaved (character+attribute) mapped at 0xB8000.
    mov dx, 0x3C4
    mov al, 0x02
    out dx, al
    inc dx
    mov al, 0x03           ; SR02: planes 0 and 1 both writable again
    out dx, al
    dec dx

    mov al, 0x04
    out dx, al
    inc dx
    mov al, 0x02           ; SR04: back to Odd/Even addressing (text mode)
    out dx, al
    dec dx

    mov dx, 0x3CE
    mov al, 0x04
    out dx, al
    inc dx
    mov al, 0x00           ; GR04: Read Map Select back to plane 0
    out dx, al
    dec dx

    mov al, 0x05
    out dx, al
    inc dx
    mov al, 0x10           ; GR05: Host Odd/Even enabled again
    out dx, al
    dec dx

    mov al, 0x06
    out dx, al
    inc dx
    mov al, 0x0E           ; GR06: Memory Map back to 0xB8000 text buffer
    out dx, al
    dec dx

    pop es
    pop ds
    pop di
    pop si
    pop dx
    pop cx
    pop ax
    ret

